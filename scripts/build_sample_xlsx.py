"""Build the synthetic Excel sample ``data/sample/orders_raw.xlsx``.

The workbook is generated by code because a realistic Excel file mixes typed
cells (real dates, numbers) with text cells, which cannot be written by hand as
text. All values are fictional. The cell content is reproducible; the file bytes
are not, because openpyxl stores the save time inside the file.

Usage (from the project root):
    python scripts/build_sample_xlsx.py            # refuses to replace an existing file
    python scripts/build_sample_xlsx.py --overwrite
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

from openpyxl import Workbook

TARGET = Path(__file__).resolve().parents[1] / "data" / "sample" / "orders_raw.xlsx"

HEADER = ["Order ID", "Order Date", "Customer ID", "SKU", "Quantity", "Unit Price", "Channel"]
ROWS = [
    # sheet row 2: typed date, numbers stored as numbers
    ["SO-1001", dt.datetime(2024, 3, 1), "000101", "AB-001", 2, 19.99, "Online"],
    # row 3: SKU with stray space and lower case; channel in lower case
    ["SO-1001", dt.datetime(2024, 3, 1), "000101", " ab-002", 1, 5, "online"],
    # row 4: European text date; customer ID stored as a NUMBER (leading zeros already lost in Excel)
    ["SO-1002", "01.03.2024", 101, "AB-001", "3", "12.50", "Store"],
    # row 5: quantity written as a word; channel upper case with trailing space
    ["SO-1003", "02.03.2024", "000103", "CD-100", "two", "1299.00", "STORE "],
    # row 6: exact duplicate of row 5
    ["SO-1003", "02.03.2024", "000103", "CD-100", "two", "1299.00", "STORE "],
    # row 7: impossible month; quantity 0; missing price
    ["SO-1004", "2024-13-01", "000104", "CD-200", 0, None, "Phone"],
    # row 8: missing order ID; channel not in the allowed list
    [None, dt.datetime(2024, 3, 5), "000105", "EF-300", 1, 7.5, "Fax"],
    # row 9: date with a time of day (no time format is configured, so it is not truncated)
    ["SO-1005", dt.datetime(2024, 3, 6, 14, 30), "000106", "EF-300", 4, 7.5, "phone"],
]


def build(target: Path) -> None:
    """Write the sample workbook to ``target``."""
    workbook = Workbook()
    notes = workbook.active
    notes.title = "Read me"
    notes.append(["Synthetic order lines for the data-cleaning toolkit demo. The data is on the 'Orders' sheet."])
    orders = workbook.create_sheet("Orders")
    orders.append(HEADER)
    for row in ROWS:
        orders.append(row)
    for cell in orders["B"][1:]:
        if isinstance(cell.value, dt.datetime):
            cell.number_format = "yyyy-mm-dd hh:mm" if cell.value.hour else "yyyy-mm-dd"
    workbook.properties.creator = "python-data-cleaning-toolkit sample generator"
    workbook.save(target)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--overwrite", action="store_true", help="replace an existing sample file")
    args = parser.parse_args()
    if TARGET.exists() and not args.overwrite:
        print(f"Error: {TARGET} already exists; use --overwrite to rebuild it.", file=sys.stderr)
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    build(TARGET)
    print(f"Wrote {TARGET.relative_to(TARGET.parents[2]).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
